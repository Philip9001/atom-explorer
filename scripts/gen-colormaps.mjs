// Generates src/physics/colormaps.ts from BIDS/colormap colormaps.py (CC0).
// Usage: node scripts/gen-colormaps.mjs /path/to/colormaps.py
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(process.argv[2], 'utf8')
function extract(name) {
  const start = src.indexOf(`_${name}_data = [`)
  if (start < 0) throw new Error(`missing ${name}`)
  const end = src.indexOf(']]', start) + 2
  const body = src.slice(start, end)
  const rows = [...body.matchAll(/\[\s*([0-9.]+),\s*([0-9.]+),\s*([0-9.]+)\s*\]/g)].map((m) => [m[1], m[2], m[3]])
  if (rows.length !== 256) throw new Error(`${name}: ${rows.length} rows`)
  return rows.flat().map((v) => Number(v).toFixed(4).replace(/\.?0+$/, '')).join(',')
}
const out = `// Generated by scripts/gen-colormaps.mjs from BIDS/colormap colormaps.py.
// Colormaps by Nathaniel J. Smith, Stefan van der Walt and Eric Firing,
// released under CC0 / public domain (https://github.com/BIDS/colormap).
// Do not edit by hand.
export type ColormapName = 'inferno' | 'magma' | 'viridis'

export const COLORMAPS: Record<ColormapName, Float32Array> = {
  inferno: new Float32Array([${extract('inferno')}]),
  magma: new Float32Array([${extract('magma')}]),
  viridis: new Float32Array([${extract('viridis')}]),
}

/** Linear lookup; t clamped to [0,1]; writes r,g,b into out[offset..offset+2]. */
export function colormapLookup(map: Float32Array, t: number, out: Float32Array, offset: number): void {
  const x = (t <= 0 ? 0 : t >= 1 ? 1 : t) * 255
  const i = Math.floor(x), f = x - i, j = Math.min(255, i + 1)
  out[offset] = map[3 * i] + (map[3 * j] - map[3 * i]) * f
  out[offset + 1] = map[3 * i + 1] + (map[3 * j + 1] - map[3 * i + 1]) * f
  out[offset + 2] = map[3 * i + 2] + (map[3 * j + 2] - map[3 * i + 2]) * f
}
`
writeFileSync(new URL('../src/physics/colormaps.ts', import.meta.url), out)
console.log('wrote src/physics/colormaps.ts')
