// Copies the marching-cubes lookup tables out of three.js (MIT) into src/physics/mcTables.ts.
// Usage: node scripts/gen-mctables.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../node_modules/three/examples/jsm/objects/MarchingCubes.js', import.meta.url), 'utf8')
function extract(name, expected) {
  const start = src.indexOf(`const ${name} = new Int32Array( [`)
  if (start < 0) throw new Error(`missing ${name}`)
  const open = src.indexOf('[', start)
  const close = src.indexOf(']', open)
  const nums = src.slice(open + 1, close).split(',').map((s) => s.replace(/\s+/g, '')).filter(Boolean).map(Number)
  if (nums.some((n) => !Number.isInteger(n))) throw new Error(`${name}: non-integer entry`)
  if (nums.length !== expected) throw new Error(`${name}: ${nums.length} entries, expected ${expected}`)
  return nums.join(',')
}
const out = `// Marching cubes lookup tables, copied from three.js examples/jsm/objects/MarchingCubes.js
// (MIT License, Copyright 2010-2026 three.js authors), which in turn follow Paul Bourke's
// "Polygonising a scalar field" (1994). Generated by scripts/gen-mctables.mjs; do not edit.
export const EDGE_TABLE = new Int32Array([${extract('edgeTable', 256)}])
export const TRI_TABLE = new Int32Array([${extract('triTable', 4096)}])
`
writeFileSync(new URL('../src/physics/mcTables.ts', import.meta.url), out)
console.log('wrote src/physics/mcTables.ts')
